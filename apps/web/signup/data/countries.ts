/**
 * Data-driven operating-defaults options for the sign-up wizard.
 *
 * Static by design: the wizard presents a real, deterministic catalogue of
 * countries (ISO-3166-1 alpha-2), their default timezone (IANA), and usable
 * currencies (ISO-4217). No component hardcodes a label; everything routes
 * through these tables (mirroring the ISO reference data in the CRM CRM/CRM
 * standards). Entries are curated to the markets MylesNet serves today plus a
 * bounded working set, kept intentionally small and reviewable.
 */

