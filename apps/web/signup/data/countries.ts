/** All currencies referenced by the country catalogue (ISO-4217 codes). */
export const CURRENCIES: readonly { code: string; name: string }[] = Array.from(
  new Set(COUNTRIES.flatMap((country) => country.currencies)),
)
  .sort()
  .map((code) => ({ code, name: CURRENCY_NAMES[code] ?? code }));

export const CURRENCY_BY_CODE: ReadonlyMap<string, string> = new Map(
  CURRENCIES.map((currency) => [currency.code, currency.name]),
);

/** Default currency code for a country: the first listed currency. */
export function defaultCurrencyForCountry(countryCode: string): string {
  return COUNTRY_BY_CODE.get(countryCode)?.currencies[0] ?? "USD";
}